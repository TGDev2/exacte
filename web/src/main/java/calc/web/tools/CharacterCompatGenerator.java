package calc.web.tools;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Writes calc.web.compat.CharacterCompat from the classification of the JDK it runs on: {@code gradlew
 * :web:generateCharacterCompat}, whose toolchain is the one of the core. It runs on the build machine and is never reached
 * from WebExports.
 */
public final class CharacterCompatGenerator {
    private static final int REFERENCE_JDK = 21;
    private static final int CODE_POINTS = 0x110000;
    private static final int ENTRIES_PER_ROW = 12;

    /** The limit of a constant in a class file, in bytes of its modified UTF-8; the table is ASCII only. */
    private static final int MAX_CONSTANT_BYTES = 65535;

    private static final String TEMPLATE = """
            package calc.web.compat;

            /**
             * The classification of code points of the JDK 21, the reference of the core, in place of the more recent one of
             * TeaVM. CompatCallRewriter sends the calls of the application here. Generated by CharacterCompatGenerator: do not
             * edit, run {@code gradlew :web:generateCharacterCompat}.
             */
            public final class CharacterCompat {
                private static final int START_DIGITS = 6;
                private static final int TYPE_DIGITS = 2;
                private static final int ENTRY = START_DIGITS + TYPE_DIGITS;
                private static final int HEXADECIMAL = 16;
                private static final int MAX_CODE_POINT = 0x10FFFF;
                private static final int UNASSIGNED = 0;
                private static final int LAST_LETTER_TYPE = 5;
                private static final int DECIMAL_DIGIT_TYPE = 9;
                private static final int FIRST_SEPARATOR_TYPE = 12;
                private static final int LAST_SEPARATOR_TYPE = 14;

                /** One entry per run of code points of the same type: the first code point of the run, then its type. */
                private static final String RUNS =
            %s;

                private static final int[] STARTS = new int[RUNS.length() / ENTRY];
                private static final byte[] TYPES = new byte[RUNS.length() / ENTRY];

                static {
                    for (int run = 0; run < STARTS.length; run++) {
                        int start = run * ENTRY;
                        STARTS[run] = Integer.parseInt(RUNS.substring(start, start + START_DIGITS), HEXADECIMAL);
                        TYPES[run] = (byte) Integer.parseInt(RUNS.substring(start + START_DIGITS, start + ENTRY), HEXADECIMAL);
                    }
                }

                private CharacterCompat() {
                }

                public static int getType(int codePoint) {
                    if (codePoint < 0 || codePoint > MAX_CODE_POINT) {
                        return UNASSIGNED;
                    }
                    int low = 0;
                    int high = STARTS.length - 1;
                    while (low < high) {
                        int middle = (low + high + 1) >>> 1;
                        if (STARTS[middle] <= codePoint) {
                            low = middle;
                        } else {
                            high = middle - 1;
                        }
                    }
                    return TYPES[low];
                }

                public static boolean isLetter(int codePoint) {
                    int type = getType(codePoint);
                    return type != UNASSIGNED && type <= LAST_LETTER_TYPE;
                }

                public static boolean isLetterOrDigit(int codePoint) {
                    return isLetter(codePoint) || getType(codePoint) == DECIMAL_DIGIT_TYPE;
                }

                public static boolean isDefined(int codePoint) {
                    return getType(codePoint) != UNASSIGNED;
                }

                public static boolean isSpaceChar(int codePoint) {
                    int type = getType(codePoint);
                    return type >= FIRST_SEPARATOR_TYPE && type <= LAST_SEPARATOR_TYPE;
                }

                /** The separators without the no-break ones, and the controls that separate. */
                public static boolean isWhitespace(int codePoint) {
                    if (codePoint == 0x00A0 || codePoint == 0x2007 || codePoint == 0x202F) {
                        return false;
                    }
                    return isSpaceChar(codePoint) || (codePoint >= 0x09 && codePoint <= 0x0D) || (codePoint >= 0x1C && codePoint <= 0x1F);
                }

                public static boolean isISOControl(int codePoint) {
                    return (codePoint >= 0 && codePoint <= 0x1F) || (codePoint >= 0x7F && codePoint <= 0x9F);
                }
            }
            """;

    private CharacterCompatGenerator() {
    }

    /** The argument is the file to write. Refuses another JDK: its table would classify differently from the core. */
    public static void main(String[] args) throws IOException {
        if (args.length != 1) {
            throw new IllegalArgumentException("Expected <output file>.");
        }
        int running = Runtime.version().feature();
        if (running != REFERENCE_JDK) {
            throw new IllegalStateException("The reference is the JDK " + REFERENCE_JDK + ", not " + running + ".");
        }
        Files.writeString(Path.of(args[0]), source(), StandardCharsets.UTF_8);
    }

    /** The whole source of the class, with line feeds. */
    public static String source() {
        String runs = runs();
        if (runs.length() > MAX_CONSTANT_BYTES) {
            throw new IllegalStateException("The table does not fit in a constant: " + runs.length() + " bytes.");
        }
        return TEMPLATE.formatted(rows(runs));
    }

    private static String runs() {
        StringBuilder runs = new StringBuilder();
        int previous = -1;
        for (int codePoint = 0; codePoint < CODE_POINTS; codePoint++) {
            int type = Character.getType(codePoint);
            if (type != previous) {
                runs.append("%06X%02X".formatted(codePoint, type));
                previous = type;
            }
        }
        return runs.toString();
    }

    /** The table cut into rows of source: a sum of literals is still one constant for the compiler. */
    private static String rows(String runs) {
        int rowLength = ENTRIES_PER_ROW * ("%06X%02X".formatted(0, 0).length());
        StringBuilder rows = new StringBuilder();
        for (int start = 0; start < runs.length(); start += rowLength) {
            rows.append(start == 0 ? "            \"" : "\n            + \"");
            rows.append(runs, start, Math.min(start + rowLength, runs.length())).append('"');
        }
        return rows.toString();
    }
}
