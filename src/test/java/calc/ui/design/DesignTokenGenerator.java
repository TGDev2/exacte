package calc.ui.design;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/**
 * Writes the files generated from {@code tokens.properties} (ADR 0016): the FlatLaf themes
 * {@code src/main/resources/calc/ui/theme/CalcLightLaf.properties} and {@code CalcDarkLaf.properties}, and
 * {@code web/site/tokens.css}. They are versioned; {@code DesignTokensAcceptanceTest} fails while one differs from this
 * output. The output is deterministic: keys in a fixed order, LF line endings, UTF-8.
 *
 * <pre>gradlew generateDesignTokens     (runs main with the repository root)</pre>
 */
public final class DesignTokenGenerator {
    static final Path LIGHT_LAF = Path.of("src", "main", "resources", "calc", "ui", "theme", "CalcLightLaf.properties");
    static final Path DARK_LAF = Path.of("src", "main", "resources", "calc", "ui", "theme", "CalcDarkLaf.properties");
    static final Path TOKENS_CSS = Path.of("web", "site", "tokens.css");

    private static final String SOURCE = "src/main/resources/calc/ui/design/tokens.properties";

    private DesignTokenGenerator() {
    }

    /** Writes the three files under the repository root {@code args[0]} (the working directory by default). */
    public static void main(String[] args) throws IOException {
        Path root = Path.of(args.length > 0 ? args[0] : ".");
        write(root.resolve(LIGHT_LAF), flatLafProperties(Theme.LIGHT));
        write(root.resolve(DARK_LAF), flatLafProperties(Theme.DARK));
        write(root.resolve(TOKENS_CSS), css());
    }

    /** The FlatLaf theme of {@code theme}: the FlatLaf variables and components it sets, then one {@code Calc.<role>} per colour role. */
    public static String flatLafProperties(Theme theme) {
        DesignTokens tokens = DesignTokens.load();
        String name = theme == Theme.LIGHT ? "CalcLightLaf" : "CalcDarkLaf";
        StringBuilder out = new StringBuilder();
        out.append("# FlatLaf theme ").append(name).append(": the ").append(theme.key()).append(" theme of the calculator.\n");
        out.append("# Generated by calc.ui.design.DesignTokenGenerator from ").append(SOURCE).append(":\n");
        out.append("# do not edit, change the tokens and run gradlew generateDesignTokens (ADR 0016).\n");
        out.append("\n# FlatLaf variables\n");
        property(out, "@background", tokens, theme, "surface.base");
        property(out, "@foreground", tokens, theme, "text.primary");
        property(out, "@accentColor", tokens, theme, "accent");
        property(out, "@selectionBackground", tokens, theme, "selection.background");
        property(out, "@selectionForeground", tokens, theme, "selection.text");
        out.append("\n# Components\n");
        property(out, "Component.focusColor", tokens, theme, "border.focus");
        property(out, "Component.borderColor", tokens, theme, "border.subtle");
        out.append("\n# The colours of the calculator, by role\n");
        for (String role : tokens.colorRoles()) {
            property(out, "Calc." + role, tokens, theme, role);
        }
        return out.toString();
    }

    /** The style sheet of the tokens: light in {@code :root}, dark in the media query, and two blocks that force a theme. */
    public static String css() {
        DesignTokens tokens = DesignTokens.load();
        StringBuilder out = new StringBuilder();
        out.append("/*\n");
        out.append(" * Design tokens of the calculator, generated by calc.ui.design.DesignTokenGenerator from\n");
        out.append(" * ").append(SOURCE).append(": do not edit, change the tokens and run\n");
        out.append(" * gradlew generateDesignTokens (ADR 0016). :root holds the light theme and the sizes, the media query the\n");
        out.append(" * dark theme; [data-theme=\"clair\"] and [data-theme=\"sombre\"] force a theme whatever the system prefers.\n");
        out.append(" */\n");
        out.append(":root {\n");
        out.append("  color-scheme: light;\n");
        colours(out, tokens, Theme.LIGHT, "  ");
        out.append("  --font-ui: ").append(family(tokens.fontFamily("ui"))).append(", system-ui, sans-serif;\n");
        out.append("  --font-mono: ").append(family(tokens.fontFamily("mono"))).append(", ui-monospace, monospace;\n");
        for (String key : tokens.sizeKeys()) {
            out.append("  --").append(key.replace('.', '-')).append(": ").append(tokens.size(key)).append("px;\n");
        }
        out.append("}\n\n");
        out.append("@media (prefers-color-scheme: dark) {\n");
        out.append("  :root {\n");
        out.append("    color-scheme: dark;\n");
        colours(out, tokens, Theme.DARK, "    ");
        out.append("  }\n");
        out.append("}\n");
        for (Theme theme : Theme.values()) {
            out.append("\n[data-theme=\"").append(theme == Theme.LIGHT ? "clair" : "sombre").append("\"] {\n");
            out.append("  color-scheme: ").append(theme.key()).append(";\n");
            colours(out, tokens, theme, "  ");
            out.append("}\n");
        }
        return out.toString();
    }

    private static void property(StringBuilder out, String key, DesignTokens tokens, Theme theme, String role) {
        out.append(key).append(" = ").append(hex(tokens, theme, role).toUpperCase(Locale.ROOT)).append('\n');
    }

    private static void colours(StringBuilder out, DesignTokens tokens, Theme theme, String indent) {
        for (String role : tokens.colorRoles()) {
            out.append(indent).append("--color-").append(role.replace('.', '-')).append(": ").append(hex(tokens, theme, role)).append(";\n");
        }
    }

    private static String hex(DesignTokens tokens, Theme theme, String role) {
        return String.format(Locale.ROOT, "#%06x", tokens.color(theme, role).getRGB() & 0xFFFFFF);
    }

    /** A CSS font family: quoted unless it is a single identifier. */
    private static String family(String name) {
        return name.matches("[A-Za-z][A-Za-z0-9-]*") ? name : "\"" + name + "\"";
    }

    private static void write(Path file, String content) throws IOException {
        Files.createDirectories(file.toAbsolutePath().getParent());
        Files.writeString(file, content, StandardCharsets.UTF_8);
        System.out.println("written " + file);
    }
}
